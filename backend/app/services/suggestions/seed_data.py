def iter_products():
    """Yield ``(category, name, unit, aliases)`` for every catalog entry."""
    for category, products in CATEGORIES.items():
        for name, unit, aliases in products:
            yield category, name, unit, aliases


def iter_pair_rules():
    """Yield ``(antecedent, consequent, weight, reason)`` for every rule."""
    for antecedent, consequents in PAIR_RULES.items():
        for consequent, weight, reason in consequents:
            yield antecedent, consequent, weight, reason


def product_count() -> int:
    return sum(len(products) for products in CATEGORIES.values())


def rule_count() -> int:
    return sum(len(consequents) for consequents in PAIR_RULES.values())
