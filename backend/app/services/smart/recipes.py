def find_recipe(goal_normalized: str) -> str | None:
    """Ключ рецепта по нормализованной цели. None — нет локального рецепта."""
    if not goal_normalized:
        return None
    for key, (_, _, aliases, _) in RECIPES.items():
        for alias in aliases:
            if alias in goal_normalized or goal_normalized in alias:
                return key
    return None


def scale_recipe(key: str, servings: int) -> tuple[str, list[tuple[str, float, str | None]]]:
    """Заголовок и масштабированные (название, кол-во, единица)."""
    title, base_servings, _, items = RECIPES[key]
    factor = servings / base_servings
    scaled = [(name, round(quantity * factor, 2), unit) for name, quantity, unit in items]
    return title, scaled
